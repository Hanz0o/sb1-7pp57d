export const DICTS: Record<LocaleCode, Dict> = { en, ar };

export function translate(locale: LocaleCode, key: string, vars?: Record<string, string>): string {
  let s = DICTS[locale][key] ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  }
  return s;
}
